"""Keep the upstream pins of the image in step with the Talos pin.

``pins/talos.Dockerfile`` holds the Talos ``imager`` pin. Dependabot updates it.
Every other pin follows from it:

- ``overlay/Dockerfile``: the ``sbc-rockchip`` overlay that Image Factory pairs
  with that Talos version for the ``rockpi4`` board.
- ``pins/sbc-rockchip.json``: the commit and build arguments that rebuild
  U-Boot from the same ``sbc-rockchip`` tag.

``pins sync`` writes both files. ``pins check`` exits 1 when they differ from
what ``sync`` would write. ``pins tag`` prints the release tag stem
``v<talos>-<overlay>`` or checks a release tag against it.
"""

import json
import os
import re
import sys
import urllib.request
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

FACTORY = "https://factory.talos.dev"
GITHUB_API = "https://api.github.com"
GITHUB_RAW = "https://raw.githubusercontent.com"
UPSTREAM_REPO = "siderolabs/sbc-rockchip"
OVERLAY_IMAGE = "ghcr.io/siderolabs/sbc-rockchip"
OVERLAY_NAME = "rockpi4"

TALOS_DOCKERFILE = Path("pins/talos.Dockerfile")
OVERLAY_DOCKERFILE = Path("overlay/Dockerfile")
BUILD_PINS = Path("pins/sbc-rockchip.json")

MAKEFILE_VARS = ("PKGS_PREFIX", "PKGS", "TOOLS_PREFIX", "TOOLS")

_TALOS_FROM = re.compile(r"^FROM ghcr\.io/siderolabs/imager:(v[0-9][^@\s]*)(@sha256:[0-9a-f]{64})?\s*$", re.M)
_OVERLAY_FROM = re.compile(rf"^FROM {re.escape(OVERLAY_IMAGE)}:(v[0-9][^@\s]*)@sha256:[0-9a-f]{{64}}\s*$", re.M)
_LAST_LINK = re.compile(r'<([^>]+)>;\s*rel="last"')

OVERLAY_TEMPLATE = """\
# Generated by `uv run pins sync`. Do not edit: CI fails when this file differs.
# The base is the sbc-rockchip overlay that Image Factory pairs with the Talos
# version in pins/talos.Dockerfile. The build context holds the patched files.
FROM {image}:{tag}@{digest}
COPY u-boot-rockchip.bin /artifacts/arm64/u-boot/rockpi4/u-boot-rockchip.bin
COPY rk3399-rock-pi-4b.dtb /artifacts/arm64/dtb/rockchip/rk3399-rock-pi-4b.dtb
"""


class PinError(Exception):
    pass


@dataclass(frozen=True)
class Response:
    body: bytes
    headers: Mapping[str, str]


Fetch = Callable[[str], Response]


@dataclass(frozen=True)
class Overlay:
    tag: str
    digest: str


def http_fetch(url: str) -> Response:
    request = urllib.request.Request(url, headers={"User-Agent": "talos-rockpi4b-pins"})
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith(GITHUB_API + "/"):
        request.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(request, timeout=30) as response:
        return Response(response.read(), dict(response.headers.items()))


def _fetch_json(fetch: Fetch, url: str):
    return json.loads(fetch(url).body)


def read_talos_tag(root: Path) -> str:
    text = (root / TALOS_DOCKERFILE).read_text()
    match = _TALOS_FROM.search(text)
    if not match:
        raise PinError(f"{TALOS_DOCKERFILE}: no FROM line for ghcr.io/siderolabs/imager")
    if not match.group(2):
        raise PinError(f"{TALOS_DOCKERFILE}: the imager pin has no sha256 digest")
    return match.group(1)


def read_overlay_tag(root: Path) -> str:
    text = (root / OVERLAY_DOCKERFILE).read_text()
    match = _OVERLAY_FROM.search(text)
    if not match:
        raise PinError(f"{OVERLAY_DOCKERFILE}: no FROM line for {OVERLAY_IMAGE} with a digest")
    return match.group(1)


def factory_overlay(talos_tag: str, fetch: Fetch) -> Overlay:
    """Return the overlay that Image Factory pairs with talos_tag for the rockpi4 board."""
    overlays = _fetch_json(fetch, f"{FACTORY}/version/{talos_tag}/overlays/official")
    for overlay in overlays:
        if overlay.get("name") != OVERLAY_NAME:
            continue
        image, _, tag = overlay["ref"].rpartition(":")
        if image != OVERLAY_IMAGE:
            raise PinError(f"Image Factory pairs {OVERLAY_NAME} with {overlay['ref']}, not {OVERLAY_IMAGE}")
        return Overlay(tag=tag, digest=overlay["digest"])
    raise PinError(f"Image Factory has no {OVERLAY_NAME} overlay for Talos {talos_tag}")


def resolve_commit(tag: str, fetch: Fetch) -> str:
    """Return the commit that tag points to. An annotated tag is dereferenced."""
    target = _fetch_json(fetch, f"{GITHUB_API}/repos/{UPSTREAM_REPO}/git/ref/tags/{tag}")["object"]
    while target["type"] == "tag":
        target = _fetch_json(fetch, f"{GITHUB_API}/repos/{UPSTREAM_REPO}/git/tags/{target['sha']}")["object"]
    if target["type"] != "commit":
        raise PinError(f"tag {tag} points to a {target['type']}, not a commit")
    return target["sha"]


def makefile_vars(text: str) -> dict[str, str]:
    """Return the default PKGS and TOOLS build arguments from the upstream Makefile."""
    found = {}
    for name in MAKEFILE_VARS:
        match = re.search(rf"^{name} \?= (\S+)\s*$", text, re.M)
        if not match:
            raise PinError(f"Makefile has no default for {name}")
        found[name] = match.group(1)
    return found


def source_date_epoch(commit: str, fetch: Fetch) -> int:
    """Return the commit time of the root commit, as the upstream Makefile does."""
    first = fetch(f"{GITHUB_API}/repos/{UPSTREAM_REPO}/commits?sha={commit}&per_page=1")
    match = _LAST_LINK.search(first.headers.get("Link", ""))
    page = _fetch_json(fetch, match.group(1)) if match else json.loads(first.body)
    root = page[-1]
    if root["parents"]:
        raise PinError(f"the oldest commit before {commit} is not a root commit: {root['sha']}")
    date = root["commit"]["committer"]["date"]
    return int(datetime.fromisoformat(date.replace("Z", "+00:00")).timestamp())


def expected_files(root: Path, fetch: Fetch) -> dict[Path, str]:
    """Return {relative path: content} for each file that sync writes."""
    overlay = factory_overlay(read_talos_tag(root), fetch)
    commit = resolve_commit(overlay.tag, fetch)
    makefile = fetch(f"{GITHUB_RAW}/{UPSTREAM_REPO}/{commit}/Makefile").body.decode()
    build_args = makefile_vars(makefile)
    build_pins = {
        "tag": overlay.tag,
        "commit": commit,
        "pkgs_prefix": build_args["PKGS_PREFIX"],
        "pkgs": build_args["PKGS"],
        "tools_prefix": build_args["TOOLS_PREFIX"],
        "tools": build_args["TOOLS"],
        "source_date_epoch": source_date_epoch(commit, fetch),
    }
    return {
        OVERLAY_DOCKERFILE: OVERLAY_TEMPLATE.format(image=OVERLAY_IMAGE, tag=overlay.tag, digest=overlay.digest),
        BUILD_PINS: json.dumps(build_pins, indent=2) + "\n",
    }


def _differs(path: Path, content: str) -> bool:
    return not path.is_file() or path.read_text() != content


def sync(root: Path, fetch: Fetch) -> list[Path]:
    """Write the pins. Return the paths that changed."""
    changed = []
    for relative, content in expected_files(root, fetch).items():
        path = root / relative
        if _differs(path, content):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            changed.append(path)
    return changed


def check(root: Path, fetch: Fetch) -> list[str]:
    """Return the relative paths that differ from what sync would write."""
    return [
        relative.as_posix()
        for relative, content in expected_files(root, fetch).items()
        if _differs(root / relative, content)
    ]


def tag_stem(root: Path) -> str:
    return f"{read_talos_tag(root)}-{read_overlay_tag(root)}"


def tag_matches(root: Path, tag: str) -> bool:
    return re.fullmatch(rf"{re.escape(tag_stem(root))}-r[1-9][0-9]*", tag) is not None


USAGE = "usage: pins sync | pins check | pins tag [RELEASE_TAG]"


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    root = Path.cwd()
    try:
        if args == ["sync"]:
            for path in sync(root, http_fetch):
                print(f"wrote {path.relative_to(root).as_posix()}")
            return 0
        if args == ["check"]:
            stale = check(root, http_fetch)
            for name in stale:
                print(f"STALE {name}: run `uv run pins sync`")
            if not stale:
                print(f"OK   pins match Image Factory for Talos {read_talos_tag(root)}")
            return 1 if stale else 0
        if args == ["tag"]:
            print(tag_stem(root))
            return 0
        if len(args) == 2 and args[0] == "tag":
            if tag_matches(root, args[1]):
                return 0
            print(f"FAIL tag {args[1]} does not match {tag_stem(root)}-r<n>", file=sys.stderr)
            return 1
    except PinError as exc:
        print(f"FAIL {exc}", file=sys.stderr)
        return 1
    print(USAGE, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
